import { type Airtable, createAirtable } from "../client.ts";
import { type CreateTableClientParams, type TableClient, createTableClient } from "./table-client.ts";
import { type TableSchemaCreate, type UpdateTableSchema } from "../tables/api.ts";
import { TableId, TableSchema } from "../tables/types.ts";
import { BaseSchema } from "../bases/types.ts";

type TableClientsByName<T extends ReadonlyArray<TableSchema>> = {
    [K in T[number]as K["name"]]: TableClient<K>;
};

type TableIdInBase<T extends BaseSchema> = T['tables'][number]['id'];

/**
 * A typed client for one base, which converts field values using the base's schema.
 *
 * `tables` maps table names to their {@link TableClient}.
 * Every method takes a single object of named parameters.
 */
export interface BaseClient<T extends BaseSchema = BaseSchema> {
    /** The schema of the base this client interacts with */
    schema: T;
    tables: TableClientsByName<T["tables"]>;
    /** The {@link Airtable} client used to make requests */
    airtable: Airtable;

    /** Create a table in the base, returning its schema. */
    createTable(params: CreateTableInBaseParams): Promise<TableSchema>;

    /** Update a table's name, description, or date dependency settings, returning its schema. */
    updateTable(params: UpdateTableInBaseParams<TableIdInBase<T>>): Promise<TableSchema>;
}

/** Parameters for {@link BaseClient.createTable}. */
export interface CreateTableInBaseParams {
    /** The table to create */
    table: TableSchemaCreate;
}

/** Parameters for {@link BaseClient.updateTable}. */
export interface UpdateTableInBaseParams<I extends TableId = TableId> {
    /** The table's ID, and the properties to change */
    table: UpdateTableSchema<I>;
}

/** Parameters for {@link createBaseClient}. */
export interface CreateBaseClientParams<T extends BaseSchema> extends Omit<CreateTableClientParams<TableSchema>, "baseId" | "schema"> {
    /** The base's schema, eg generated by `airtable-kit codegen` or from `airtable.bases.get()` */
    schema: T;
}

/**
 * Create a typed {@link BaseClient}, which converts field values using the base's schema.
 *
 * ```typescript
 * import { createBaseClient } from 'airtable-kit/typed';
 * import myBaseSchema from './schemas/myBase';
 *
 * const myBase = createBaseClient({ schema: myBaseSchema }); // reads AIRTABLE_API_KEY
 * const myBase = createBaseClient({ schema: myBaseSchema, airtable: { apiKey: "patXXX" } });
 * const myBase = createBaseClient({ schema: myBaseSchema, airtable }); // share one client across bases
 * await myBase.tables.tasks.listRecords();
 * ```
 *
 * `airtable` and `onReadUnexpectedField` apply to every table.
 */
export function createBaseClient<T extends BaseSchema>(params: CreateBaseClientParams<T>): BaseClient<T> {
    const { schema: baseSchema, ...options } = params;
    const client = createAirtable(options.airtable);
    const tables = Object.fromEntries(
        baseSchema.tables.map((tableSchema) => [
            tableSchema.name,
            createTableClient({ ...options, baseId: baseSchema.id, schema: tableSchema, airtable: client }),
        ]),
    ) as TableClientsByName<T["tables"]>;
    return {
        schema: baseSchema,
        tables,
        airtable: client,
        createTable({ table }) {
            return client.tables.create({ baseId: baseSchema.id, table });
        },
        updateTable({ table }) {
            return client.tables.update({ baseId: baseSchema.id, table });
        },
    };
}
