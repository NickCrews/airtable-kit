import { type Airtable, createAirtable } from "../client.ts";
import { type TableClient, type TypedClientOptions, createTableClient } from "./table-client.ts";
import { type TableSchemaCreate, type UpdateTableSchema } from "../tables/api.ts";
import { TableSchema } from "../tables/types.ts";
import { BaseSchema } from "../bases/types.ts";

type TableClientsByName<T extends ReadonlyArray<TableSchema>> = {
    [K in T[number]as K["name"]]: TableClient<K>;
};

type TableIdInBase<T extends BaseSchema> = T['tables'][number]['id'];

/**
 * A typed client for one base, which converts field values using the base's schema.
 *
 * `tables` maps table names to their {@link TableClient}.
 */
export interface BaseClient<T extends BaseSchema = BaseSchema> {
    /** The schema of the base this client interacts with */
    schema: T;
    tables: TableClientsByName<T["tables"]>;
    /** The {@link Airtable} client used to make requests */
    airtable: Airtable;

    /** Create a table in the base
     * 
     * @param tableSchema The schema of the table to create
     * @returns The created table's schema
     */
    createTable(tableSchema: TableSchemaCreate): Promise<TableSchema>;

    /** Update a table's name, description, or date dependency settings
     * 
     * @param tableSchema The updated schema of the table
     * @returns The updated table's schema
     */
    updateTable(tableSchema: UpdateTableSchema<TableIdInBase<T>>): Promise<TableSchema>;
}

/** Options for {@link createBaseClient}. */
export interface BaseClientOptions extends TypedClientOptions { }

/**
 * Create a typed {@link BaseClient}, which converts field values using the base's schema.
 *
 * ```typescript
 * import { createBaseClient } from 'airtable-kit/typed';
 * import myBaseSchema from './schemas/myBase';
 *
 * const myBase = createBaseClient(myBaseSchema); // reads AIRTABLE_API_KEY
 * const myBase = createBaseClient(myBaseSchema, { airtable: { apiKey: "patXXX" } });
 * const myBase = createBaseClient(myBaseSchema, { airtable }); // share one client across bases
 * await myBase.tables.tasks.listRecords();
 * ```
 *
 * @param baseSchema - The base's schema, eg generated by `airtable-kit codegen` or from `airtable.bases.get()`
 * @param options - See {@link BaseClientOptions}. Applied to every table.
 */
export function createBaseClient<T extends BaseSchema>(
    baseSchema: T,
    options: BaseClientOptions = {},
): BaseClient<T> {
    const client = createAirtable(options.airtable);
    const tables = Object.fromEntries(
        baseSchema.tables.map((tableSchema) => [
            tableSchema.name,
            createTableClient(tableSchema, { ...options, baseId: baseSchema.id, airtable: client }),
        ]),
    ) as TableClientsByName<T["tables"]>;
    return {
        schema: baseSchema,
        tables,
        airtable: client,
        createTable(tableSchema) {
            return client.tables.create({ baseId: baseSchema.id, table: tableSchema });
        },
        updateTable(tableSchema) {
            return client.tables.update({ baseId: baseSchema.id, table: tableSchema });
        },
    };
}
